import {fileURLToPath} from 'node:url';
import {defineConfig} from 'vite';
import react, {reactCompilerPreset} from '@vitejs/plugin-react';
import babel from '@rolldown/plugin-babel';

const srcDir = fileURLToPath(new URL('./src/', import.meta.url));

// React Compiler (babel-plugin-react-compiler 1.0) auto-memoizes components and hooks.
// It relies on the Rules of React (never mutate state or props; see store/ledgerStore.js),
// which `npm run lint` checks and `npm run check:compiler` verifies. Only the app's own
// React code is compiled: not src/core/classic/ (the original app's plain scripts) or
// src/themes/ (generated by the Astryx theme editor).
const escape = path => path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const compiler = reactCompilerPreset();
compiler.rolldown.filter.id = {
  include: new RegExp(`^${escape(srcDir)}.*\\.jsx?$`),
  exclude: new RegExp(`^${escape(srcDir)}(core/classic|themes)/`),
};

export default defineConfig({
  // Relative asset paths, so the build works wherever it's served from: the site root on
  // Vercel, or the desktop launcher's local server.
  base: './',
  plugins: [react(), babel({presets: [compiler]})],
});
